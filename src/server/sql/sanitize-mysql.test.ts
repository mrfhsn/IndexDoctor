import { describe, it, expect } from 'vitest';

import { sanitizeMysql } from './sanitize-mysql.js';

describe('MySQL Sanitizer (sql/sanitize-mysql.ts)', () => {
  it('leaves standard PostgreSQL SQL unchanged with zero notices', () => {
    const pgSql = 'CREATE TABLE users (id SERIAL PRIMARY KEY, created_at TIMESTAMPTZ);';
    const result = sanitizeMysql(pgSql);
    expect(result.sql).toBe(pgSql);
    expect(result.notices).toHaveLength(0);
  });

  it('replaces backticks with standard double quotes and emits notice', () => {
    const mysql = 'CREATE TABLE `orders` (`id` INT, `status` VARCHAR(255));';
    const result = sanitizeMysql(mysql);
    expect(result.sql).toContain('"orders"');
    expect(result.sql).toContain('"id"');
    expect(result.sql).not.toContain('`');
    expect(result.notices).toContain('Rewrote MySQL backticks to standard double quotes.');
  });

  it('converts DATETIME to TIMESTAMP and emits notice', () => {
    const mysql = 'CREATE TABLE events (event_time DATETIME NOT NULL);';
    const result = sanitizeMysql(mysql);
    expect(result.sql).toContain('TIMESTAMP NOT NULL');
    expect(result.notices).toContain('Converted MySQL DATETIME type to TIMESTAMP.');
  });

  it('converts AUTO_INCREMENT to SERIAL / IDENTITY and emits notice', () => {
    const mysql = 'CREATE TABLE items (id INT AUTO_INCREMENT PRIMARY KEY);';
    const result = sanitizeMysql(mysql);
    expect(result.sql).not.toContain('AUTO_INCREMENT');
    expect(result.sql).toContain('id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
    expect(result.notices).toContain('Converted MySQL AUTO_INCREMENT to standard identity.');
  });

  it('strips MySQL ENGINE, CHARSET, and COLLATE table options', () => {
    const mysql =
      'CREATE TABLE logs (id INT) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;';
    const result = sanitizeMysql(mysql);
    expect(result.sql).not.toContain('ENGINE=InnoDB');
    expect(result.sql).not.toContain('DEFAULT CHARSET');
    expect(result.sql).not.toContain('COLLATE=utf8mb4_unicode_ci');
    expect(result.notices.length).toBeGreaterThan(0);
  });
});
