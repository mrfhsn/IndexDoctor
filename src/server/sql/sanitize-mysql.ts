export interface SanitizedSqlResult {
  sql: string;
  notices: string[];
}

/**
 * Best-effort sanitizer for MySQL DDL constructs before AST parsing.
 * Converts common MySQL idiosyncrasies into standard PostgreSQL syntax
 * and records descriptive notices for the user.
 */
export function sanitizeMysql(inputSql: string): SanitizedSqlResult {
  let sql = inputSql;
  const notices: string[] = [];

  // 1. Backticks -> standard double quotes
  if (sql.includes('`')) {
    sql = sql.replace(/`([^`]+)`/g, '"$1"');
    notices.push('Rewrote MySQL backticks to standard double quotes.');
  }

  // 2. AUTO_INCREMENT -> GENERATED BY DEFAULT AS IDENTITY
  if (/AUTO_INCREMENT/i.test(sql)) {
    sql = sql.replace(/\bAUTO_INCREMENT\b/gi, 'GENERATED BY DEFAULT AS IDENTITY');
    notices.push('Converted MySQL AUTO_INCREMENT to standard identity.');
  }

  // 3. DATETIME -> TIMESTAMP
  if (/\bDATETIME\b/i.test(sql)) {
    sql = sql.replace(/\bDATETIME\b/gi, 'TIMESTAMP');
    notices.push('Converted MySQL DATETIME type to TIMESTAMP.');
  }

  // 4. ENGINE=...
  if (/\bENGINE\s*=\s*\w+/i.test(sql)) {
    sql = sql.replace(/\s*\bENGINE\s*=\s*\w+/gi, '');
    notices.push('Removed MySQL ENGINE table options.');
  }

  // 5. DEFAULT CHARSET=... / CHARSET=...
  if (/\b(?:DEFAULT\s+)?CHARSET\s*=\s*[\w-]+/i.test(sql)) {
    sql = sql.replace(/\s*\b(?:DEFAULT\s+)?CHARSET\s*=\s*[\w-]+/gi, '');
    notices.push('Removed MySQL CHARSET table options.');
  }

  // 6. COLLATE=...
  if (/\bCOLLATE\s*=\s*[\w-]+/i.test(sql)) {
    sql = sql.replace(/\s*\bCOLLATE\s*=\s*[\w-]+/gi, '');
    notices.push('Removed MySQL COLLATE table options.');
  }

  return { sql, notices };
}
